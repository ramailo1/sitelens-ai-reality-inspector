// REPORT CONTRACT

export interface OfflineRegressionCase {
  readonly id: string;
  readonly description: string;
  readonly passed: boolean;
  readonly detail: string;
}

export interface OfflineCaseOutcome {
  readonly caseId: string;
  readonly requestSucceeded: boolean;
  readonly error: string | null;
  readonly observationsAccepted: number;
  readonly observationsRejected: number;
  // Trust invariants: origin and verification status of every observation.
  readonly allAiGenerated: boolean;
  readonly allUnverified: boolean;
  readonly isDemoFixture: boolean;
  // Deterministic comparison verdicts, in reference order.
  readonly comparisonStatuses: readonly string[];
  readonly comparisonCorrect: number;
  readonly comparisonTotal: number;
}

export interface EvaluationReport {
  readonly mode: 'offline' | 'live';
  readonly manifestVersion: string;
  readonly datasetVersion: string;
  readonly provider: { readonly name: string; readonly model: string };
  readonly runAt: string;
  readonly sampleCounts: {
    readonly manifestCases: number;
    readonly evaluated: number;
    readonly uncertain: number;
    readonly excluded: number;
    readonly liveOnly: number;
  };
  readonly cases: readonly OfflineCaseOutcome[];
  readonly regressionCases: readonly OfflineRegressionCase[];
  readonly metrics: {
    // Trust-boundary conformance across evaluated cases (1 = perfect).
    readonly trustConformance: number;
    // Deterministic comparison rows matching their authored labels.
    readonly comparisonCorrectness: { readonly correct: number; readonly total: number };
    // Regression scenarios passed.
    readonly regressionPassed: { readonly passed: number; readonly total: number };
    // Live-only accuracy metrics; null in offline mode by design.
    readonly observationPrecision: number | null;
    readonly observationRecall: number | null;
  };
  readonly limitations: readonly string[];
}

// Per-case offline outcome: trust invariants plus comparison arithmetic.
async function offlineCase(
  testCase: EvalCase,
  capture: DemoCapture,
): Promise<OfflineCaseOutcome> {
  const inspector = new RealityInspector({ provider: new DemoFixtureProvider() });
  try {
    const result = await inspector.inspectCapture({
      image: { bytes: capture.bytes, mediaType: capture.mediaType, captureId: capture.id },
      projectId: 'proj_eval_' + testCase.id,
      zoneId: 'zone_eval',
    });
    const rows: readonly ComparisonRow[] = compareExpectedState(OFFLINE_REFERENCE, result.elements ?? []);
    let correct = 0;
    for (const row of rows) {
      if (OFFLINE_COMPARISON_LABELS[row.expectedId] === row.status) correct += 1;
    }
    return {
      caseId: testCase.id,
      requestSucceeded: true,
      error: null,
      observationsAccepted: result.observations.length,
      observationsRejected: result.rejected.length,
      allAiGenerated: result.observations.every((o) => o.origin === 'AI_GENERATED'),
      allUnverified: result.observations.every((o) => o.verificationStatus === 'UNVERIFIED'),
      isDemoFixture: result.provider === 'demo-fixture',
      comparisonStatuses: rows.map((r) => r.status),
      comparisonCorrect: correct,
      comparisonTotal: rows.length,
    };
  } catch (error: unknown) {
    const kind = error instanceof ProviderError ? error.kind : 'ERROR';
    return {
      caseId: testCase.id,
      requestSucceeded: false,
      error: `${kind}: ${error instanceof Error ? error.message : String(error)}`,
      observationsAccepted: 0,
      observationsRejected: 0,
      allAiGenerated: true,
      allUnverified: true,
      isDemoFixture: true,
      comparisonStatuses: [],
      comparisonCorrect: 0,
      comparisonTotal: OFFLINE_REFERENCE.items.length,
    };
  }
}

