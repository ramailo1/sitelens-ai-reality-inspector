// Deterministic regression scenarios for the failure modes the evaluation must never stop catching: unsupported.
export async function runRegressionScenarios(): Promise<OfflineRegressionCase[]> {
  const cases: OfflineRegressionCase[] = [];

  // 1. Unsupported observations: an entry that asserts nothing, or that contradicts itself, is rejected rather than.
  const zeroConfidence = validateDetectedElement({
    element: 'SLAB', present: true, count: null, confidence: 0,
    evidence: 'no visible slab', bounding_box: null,
  });
  const selfContradicting = validateDetectedElement({
    element: 'SLAB', present: true, count: null, confidence: 0.9,
    evidence: 'no visible slab', bounding_box: null,
  });
  const genuineObservation = validateModelObservation({
    category: 'OBSERVED_ELEMENT', observation: 'A slab deck is visible.', evidence: { description: 'deck' },
    confidence: 0.4, severity: 'INFO', suggested_action: 'NO_ACTION',
  });
  cases.push({
    id: 'unsupported-observation-rejected',
    description: 'Zero-confidence template echoes and self-contradictory entries never survive validation.',
    passed: zeroConfidence.ok === false && selfContradicting.ok === false && genuineObservation.ok === true,
    detail: `zeroConfidence.ok=${zeroConfidence.ok} selfContradicting.ok=${selfContradicting.ok} `
      + `genuineObservation.ok=${genuineObservation.ok}`,
  });

  // 2. Insufficient evidence: an element the capture never showed yields UNDETERMINED — not MATCH, not a fabricated shortfall.
  const inspector = new RealityInspector({ provider: new DemoFixtureProvider() });
  const fixtureResult = await inspector.inspectCapture({
    image: { bytes: Buffer.alloc(8, 7), mediaType: 'image/png', captureId: 'cap_eval_stub' },
    projectId: 'proj_eval_regression',
    zoneId: 'zone_eval',
  });
  const rows = compareExpectedState(OFFLINE_REFERENCE, fixtureResult.elements ?? []);
  const excavationRow = rows.filter((r) => r.expectedId === 'ev_excavation')[0];
  cases.push({
    id: 'insufficient-evidence-undetermined',
    description: 'An expected element with no visual reading at all is UNDETERMINED, never MATCH or ATTENTION.',
    passed: excavationRow !== undefined && excavationRow.status === 'UNDETERMINED',
    detail: `ev_excavation status=${excavationRow === undefined ? 'missing' : excavationRow.status}`,
  });

  // 3. Malformed provider responses fail closed: nothing is accepted, every malformed entry is retained in the rejection.
  let malformedResult: { observations: number; rejected: number } | null = null;
  let malformedDetail = 'request unexpectedly failed';
  try {
    const malformedRun = await new RealityInspector({ provider: malformedProvider }).inspectCapture({
      image: { bytes: Buffer.alloc(8, 7), mediaType: 'image/png', captureId: 'cap_eval_malformed' },
    });
    malformedResult = {
      observations: malformedRun.observations.length,
      rejected: malformedRun.rejected.length,
    };
    malformedDetail = `accepted=${malformedResult.observations} rejected=${malformedResult.rejected}`;
  } catch (error: unknown) {
    // A hard ProviderError is also acceptable fail-closed behavior; the request simply never yielded observations.
    const kind = error instanceof ProviderError ? error.kind : String(error);
    malformedResult = { observations: 0, rejected: 0 };
    malformedDetail = `ProviderError(${kind})`;
  }
  cases.push({
    id: 'malformed-response-fails-closed',
    description: 'A structurally invalid provider response yields no observations and reports every rejection.',
    passed: malformedResult !== null && malformedResult.observations === 0 && malformedResult.rejected >= 1,
    detail: malformedDetail,
  });

  // 4. Reasoning prose cannot overwrite the canonical comparison, the detections, or the human-verification boundary .
  const capture = demoCaptures()[0]!;
  const session = new InspectionSession(
    new DemoFixtureProvider(),
    capture,
    'proj_eval_overstate',
    'zone_eval',
    OFFLINE_REFERENCE,
    { reasoner: new OverstatingReasoner() },
  );
  const view = await session.run();
  const statusesMatch = view.comparison.length === OFFLINE_REFERENCE.items.length
    && view.comparison.every((row, i) =>
      row.status === OFFLINE_COMPARISON_LABELS[OFFLINE_REFERENCE.items[i]!.id]);
  const nothingSelfVerified =
    view.observations.every((o) => o.verificationStatus === 'UNVERIFIED')
    && view.inspectionFindings.every((f) => f.verificationStatus === 'UNVERIFIED');
  cases.push({
    id: 'reasoning-overstatement-cannot-verify',
    description: 'Reasoning that claims compliance never changes comparison verdicts or verifies anything.',
    passed: statusesMatch && nothingSelfVerified && view.reasoning.status === 'AVAILABLE',
    detail: `statusesMatch=${statusesMatch} nothingSelfVerified=${nothingSelfVerified} `
      + `reasoning=${view.reasoning.status}`,
  });

  return cases;
}

// The deterministic offline evaluation.
export async function runOfflineEvaluation(): Promise<EvaluationReport> {
  const demoById = new Map(demoCaptures().map((c) => [c.id, c] as const));
  const outcomes: OfflineCaseOutcome[] = [];
  for (const testCase of EVALUATION_MANIFEST.filter((c) => c.mode === 'offline')) {
    const capture = demoById.get(testCase.captureId);
    if (capture === undefined) {
      outcomes.push({
        caseId: testCase.id,
        requestSucceeded: false,
        error: 'MANIFEST_MISSING_CAPTURE: no generated capture with id ' + testCase.captureId,
        observationsAccepted: 0,
        observationsRejected: 0,
        allAiGenerated: true,
        allUnverified: true,
        isDemoFixture: true,
        comparisonStatuses: [],
        comparisonCorrect: 0,
        comparisonTotal: OFFLINE_REFERENCE.items.length,
      });
      continue;
    }
    outcomes.push(await offlineCase(testCase, capture));
  }

  const regressionCases = await runRegressionScenarios();
  const evaluated = outcomes.length;
  const trustHeld = outcomes.filter((o) => o.allAiGenerated && o.allUnverified).length;
  const correct = outcomes.reduce((sum, o) => sum + o.comparisonCorrect, 0);
  const total = outcomes.reduce((sum, o) => sum + o.comparisonTotal, 0);
  const regressionPassed = regressionCases.filter((c) => c.passed).length;
  const uncertain = EVALUATION_MANIFEST.filter((c) => c.uncertainReason !== undefined).length;

  return {
    mode: 'offline',
    manifestVersion: EVAL_MANIFEST_VERSION,
    datasetVersion: EVAL_DATASET_VERSION,
    provider: { name: 'demo-fixture', model: 'demo-fixture-vision-v1' },
    runAt: new Date().toISOString(),
    sampleCounts: {
      manifestCases: EVALUATION_MANIFEST.length,
      evaluated,
      uncertain,
      excluded: uncertain,
      liveOnly: EVALUATION_MANIFEST.filter((c) => c.mode === 'live-only').length,
    },
    cases: outcomes,
    regressionCases,
    metrics: {
      trustConformance: evaluated === 0 ? 0 : trustHeld / evaluated,
      comparisonCorrectness: { correct, total },
      regressionPassed: { passed: regressionPassed, total: regressionCases.length },
      observationPrecision: null,
      observationRecall: null,
    },
    limitations: [
      'Offline mode measures specification conformance, not model accuracy: the fixture provider returns fixed synthetic content and is not a vision model.',
      'Element-level precision and recall are only computed in live mode, where a real model produces the output being scored.',
      'A small synthetic sample cannot prove general model accuracy; metrics are descriptive, not statistically conclusive.',
      'Sample-dataset cases (007, 013, 022) are excluded from offline scoring and carry their own uncertainty flags for live evaluation.',
    ],
  };
}

// LIVE (OPT-IN) SCORING Only reachable through an explicit invocation with an already configured provider.

export interface LiveCaseScore {
  readonly caseId: string;
  readonly requestSucceeded: boolean;
  readonly error: string | null;
  readonly accepted: number;
  readonly rejected: number;
  // Element metrics over definitive labels only.
  readonly supportedElements: readonly string[];
  readonly unsupportedElements: readonly string[];
  readonly unlabeledDetections: readonly string[];
  readonly expectedPresentElements: readonly string[];
  readonly missedExpectedElements: readonly string[];
  readonly evidenceCoverageExpected: EvidenceCoverage;
  readonly evidenceCoverageObserved: 'localized' | 'fullFrame' | 'none' | 'uncertain';
  readonly reviewBoundaryHeld: boolean;
  // True when uncertainty removes this case from a definitive metric.
  readonly excludedFromElementMetrics: boolean;
}

// Read the image bytes for a manifest case from its authoritative source.
function caseBytes(testCase: EvalCase, sampleDir: string): Buffer | null {
  if (testCase.source.kind === 'synthetic-demo') {
    const capture = demoCaptures().find((c) => c.id === testCase.captureId);
    return capture === undefined ? null : capture.bytes;
  }
  const fileName = testCase.source.origin.replace(/^sample\//, '');
  try {
    return readFileSync(join(sampleDir, fileName));
  } catch {
    return null;
  }
}

// Score one live run of one case against its human-authored labels.
export function scoreLiveCase(
  testCase: EvalCase,
  result: {
    readonly observations: readonly { verificationStatus: string; origin: string }[];
    readonly elements?: readonly { element: string; present: boolean; boundingBox: unknown }[];
  },
): LiveCaseScore {
  const labelsByElement = new Map(testCase.labels.expectedElements.map((l) => [l.element, l] as const));
  const supported: string[] = [];
  const unsupported: string[] = [];
  const unlabeled: string[] = [];
  const expectedPresent: string[] = [];
  const detectedExpected: string[] = [];
  for (const label of testCase.labels.expectedElements) {
    if (label.presence === 'present') expectedPresent.push(label.element);
  }
  const detections = result.elements ?? [];
  for (const detection of detections) {
    if (!detection.present) continue;
    const label = labelsByElement.get(detection.element);
    if (label === undefined) {
      unlabeled.push(detection.element);
    } else if (label.presence === 'present') {
      supported.push(detection.element);
      detectedExpected.push(detection.element);
    } else if (label.presence === 'absent') {
      unsupported.push(detection.element);
    } else {
      // uncertain label: neither supported nor unsupported
      unlabeled.push(detection.element);
    }
  }
  const missed = expectedPresent.filter((e) => !detectedExpected.includes(e));
  const anyBox = detections.some((d) => d.boundingBox !== null && d.boundingBox !== undefined)
    || result.observations.length > 0;
  const observedCoverage: LiveCaseScore['evidenceCoverageObserved'] =
    anyBox ? 'localized' : detections.length > 0 ? 'fullFrame' : 'none';
  return {
    caseId: testCase.id,
    requestSucceeded: true,
    error: null,
    accepted: result.observations.length,
    rejected: 0,
    supportedElements: supported,
    unsupportedElements: unsupported,
    unlabeledDetections: unlabeled,
    expectedPresentElements: expectedPresent,
    missedExpectedElements: missed,
    evidenceCoverageExpected: testCase.labels.evidenceCoverage,
    evidenceCoverageObserved: observedCoverage,
    reviewBoundaryHeld:
      result.observations.every((o) => o.verificationStatus === 'UNVERIFIED' && o.origin === 'AI_GENERATED'),
    excludedFromElementMetrics: testCase.uncertainReason !== undefined,
  };
}

// THE OPT-IN LIVE EVALUATION.
export async function runLiveEvaluation(
  provider: AIProvider,
  options: { readonly sampleDir?: string } = {},
): Promise<EvaluationReport & { readonly liveScores: readonly LiveCaseScore[] }> {
  const sampleDir = options.sampleDir ?? 'sample';
  const outcomes: OfflineCaseOutcome[] = [];
  const liveScores: LiveCaseScore[] = [];

  const failedScore = (testCase: EvalCase, err: string): LiveCaseScore => ({
    caseId: testCase.id, requestSucceeded: false, error: err, accepted: 0, rejected: 0,
    supportedElements: [], unsupportedElements: [], unlabeledDetections: [],
    expectedPresentElements: [], missedExpectedElements: [],
    evidenceCoverageExpected: testCase.labels.evidenceCoverage,
    evidenceCoverageObserved: 'uncertain', reviewBoundaryHeld: true,
    excludedFromElementMetrics: true,
  });
  const failedOutcome = (testCase: EvalCase, err: string): OfflineCaseOutcome => ({
    caseId: testCase.id, requestSucceeded: false, error: err,
    observationsAccepted: 0, observationsRejected: 0,
    allAiGenerated: true, allUnverified: true, isDemoFixture: false,
    comparisonStatuses: [], comparisonCorrect: 0,
    comparisonTotal: OFFLINE_REFERENCE.items.length,
  });

  for (const testCase of EVALUATION_MANIFEST) {
    const bytes = caseBytes(testCase, sampleDir);
    if (bytes === null) {
      const err = 'IMAGE_UNAVAILABLE: ' + testCase.source.origin + ' could not be read';
      outcomes.push(failedOutcome(testCase, err));
      liveScores.push(failedScore(testCase, err));
      continue;
    }
    const inspector = new RealityInspector({ provider });
    try {
      const result = await inspector.inspectCapture({
        image: { bytes, mediaType: 'image/jpeg', captureId: testCase.captureId },
        projectId: 'proj_eval_live',
        zoneId: 'zone_eval',
      });
      const rows = compareExpectedState(OFFLINE_REFERENCE, result.elements ?? []);
      outcomes.push({
        caseId: testCase.id, requestSucceeded: true, error: null,
        observationsAccepted: result.observations.length,
        observationsRejected: result.rejected.length,
        allAiGenerated: result.observations.every((o) => o.origin === 'AI_GENERATED'),
        allUnverified: result.observations.every((o) => o.verificationStatus === 'UNVERIFIED'),
        isDemoFixture: result.provider === 'demo-fixture',
        comparisonStatuses: rows.map((r) => r.status),
        comparisonCorrect: 0, comparisonTotal: 0,
      });
      liveScores.push(scoreLiveCase(testCase, result));
    } catch (error: unknown) {
      const kind = error instanceof ProviderError ? error.kind : 'ERROR';
      const err = `${kind}: ${error instanceof Error ? error.message : String(error)}`;
      outcomes.push(failedOutcome(testCase, err));
      liveScores.push(failedScore(testCase, err));
    }
  }

  const scored = liveScores.filter((s) => s.requestSucceeded && !s.excludedFromElementMetrics);
  const totalSupported = scored.reduce((n, s) => n + s.supportedElements.length, 0);
  const totalUnsupported = scored.reduce((n, s) => n + s.unsupportedElements.length, 0);
  const totalExpected = scored.reduce((n, s) => n + s.expectedPresentElements.length, 0);
  const totalMissed = scored.reduce((n, s) => n + s.missedExpectedElements.length, 0);
  const precisionDenominator = totalSupported + totalUnsupported;
  const regressionCases = await runRegressionScenarios();

  return {
    mode: 'live',
    manifestVersion: EVAL_MANIFEST_VERSION,
    datasetVersion: EVAL_DATASET_VERSION,
    provider: { name: provider.name, model: provider.model },
    runAt: new Date().toISOString(),
    sampleCounts: {
      manifestCases: EVALUATION_MANIFEST.length,
      evaluated: liveScores.filter((s) => s.requestSucceeded).length,
      uncertain: EVALUATION_MANIFEST.filter((c) => c.uncertainReason !== undefined).length,
      excluded: liveScores.filter((s) => s.excludedFromElementMetrics).length,
      liveOnly: EVALUATION_MANIFEST.filter((c) => c.mode === 'live-only').length,
    },
    cases: outcomes,
    regressionCases,
    metrics: {
      trustConformance: outcomes.length === 0 ? 0
        : outcomes.filter((o) => o.allAiGenerated && o.allUnverified).length / outcomes.length,
      // Comparison verdicts over live detections are reported per case but not scored: with a real model, verdict differences.
      comparisonCorrectness: { correct: 0, total: 0 },
      regressionPassed: {
        passed: regressionCases.filter((c) => c.passed).length,
        total: regressionCases.length,
      },
      observationPrecision: precisionDenominator === 0 ? null : totalSupported / precisionDenominator,
      observationRecall: totalExpected === 0 ? null : (totalExpected - totalMissed) / totalExpected,
    },
    limitations: [
      'Live metrics are computed over a small manifest sample and are descriptive, not statistically conclusive.',
      'Unlabeled detections (elements the manifest does not label) are reported separately and never counted as unsupported.',
      'Uncertain cases and uncertain element labels are excluded from precision and recall; they are listed with reasons.',
      'Comparison verdicts over live detections are reported per case but not scored as correctness.',
    ],
    liveScores,
  };
}

// A readable, reproducible report.
export function formatEvaluationReport(report: EvaluationReport): string {
  const lines: string[] = [];
  const pct = (v: number | null): string => (v === null ? 'n/a (live mode only)' : `${(v * 100).toFixed(1)}%`);
  lines.push('# SiteLens evaluation report');
  lines.push('');
  lines.push(`- mode: ${report.mode}`);
  lines.push(`- run at: ${report.runAt}`);
  lines.push(`- manifest version: ${report.manifestVersion}`);
  lines.push(`- dataset: ${report.datasetVersion}`);
  lines.push(`- provider: ${report.provider.name}`);
  lines.push(`- model: ${report.provider.model}`);
  lines.push('');
  lines.push('## Sample counts');
  lines.push('');
  lines.push(`- manifest cases: ${report.sampleCounts.manifestCases}`);
  lines.push(`- evaluated: ${report.sampleCounts.evaluated}`);
  lines.push(`- uncertain (excluded from definitive metrics): ${report.sampleCounts.uncertain}`);
  lines.push(`- live-only (not scored offline): ${report.sampleCounts.liveOnly}`);
  lines.push('');
  lines.push('## Metrics');
  lines.push('');
  lines.push(`- trust-boundary conformance: ${pct(report.metrics.trustConformance)}`);
  lines.push(`- deterministic comparison correctness: ${report.metrics.comparisonCorrectness.correct}/${report.metrics.comparisonCorrectness.total}`);
  lines.push(`- regression scenarios passed: ${report.metrics.regressionPassed.passed}/${report.metrics.regressionPassed.total}`);
  lines.push(`- observation precision: ${pct(report.metrics.observationPrecision)}`);
  lines.push(`- observation recall: ${pct(report.metrics.observationRecall)}`);
  lines.push('');
  lines.push('## Cases');
  lines.push('');
  for (const c of report.cases) {
    const detail = c.requestSucceeded
      ? ` (observations ${c.observationsAccepted} accepted / ${c.observationsRejected} rejected;`
        + ` comparison ${c.comparisonCorrect}/${c.comparisonTotal} labelled rows)`
      : ` — ${c.error ?? 'unknown error'}`;
    lines.push(`- ${c.caseId}: ${c.requestSucceeded ? 'ok' : 'FAILED'}${detail}`);
  }
  lines.push('');
  lines.push('## Regression scenarios');
  lines.push('');
  for (const r of report.regressionCases) {
    lines.push(`- ${r.passed ? 'PASS' : 'FAIL'} ${r.id}: ${r.detail}`);
  }
  lines.push('');
  lines.push('## Known limitations');
  lines.push('');
  for (const l of report.limitations) lines.push(`- ${l}`);
  lines.push('');
  return lines.join('\n');
}
