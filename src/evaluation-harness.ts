export type ElementPresence = 'present' | 'absent' | 'uncertain';
export type EvidenceCoverage = 'localized' | 'fullFrame' | 'none' | 'uncertain';

// Human-authored label for one element kind in one image.
export interface ElementLabel {
  readonly element: string;
  readonly presence: ElementPresence;
  // Known count when the image genuinely fixes one; null when it does not.
  readonly count?: number | null;
  // Where the label comes from. Never "the model said so".
  readonly basis: string;
}

// The label set for one evaluation case.
export interface EvalCaseLabels {
  readonly expectedElements: readonly ElementLabel[];
  readonly evidenceCoverage: EvidenceCoverage;
  // Whether the case defensibly requires a human review to settle.
  readonly humanReviewRequired: boolean;
}

export interface EvalCase {
  readonly id: string;
  readonly captureId: string;
  readonly description: string;
  readonly focus: readonly string[];
  readonly source: {
    readonly kind: 'synthetic-demo' | 'sample-dataset';
    readonly licence: string;
    // File name for dataset cases; generation module for synthetic ones.
    readonly origin: string;
  };
  // offline: fixture-scoreable synthetic capture, evaluated in the default run.
  readonly mode: 'offline' | 'live-only';
  readonly labels: EvalCaseLabels;
  // Present only when the case is excluded from definitive metrics.
  readonly uncertainReason?: string;
}

